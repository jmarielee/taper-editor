#!/usr/bin/env python3
"""Convert the Figma token exports in tokens/ into build/tokens.css.

The exports use the W3C design tokens format: one folder per collection,
one file per mode. A collection with a single mode goes under :root. A
collection with Light and Dark modes puts Light under :root and Dark under
both @media (prefers-color-scheme: dark) and [data-theme="dark"].

Usage: python3 build-tokens.py
"""

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOKENS = HERE / "tokens"
OUT = HERE / "build" / "tokens.css"

COLLECTIONS = ["verdict", "dimensions"]

GOOGLE_FONTS = (
    "https://fonts.googleapis.com/css2"
    "?family=Barlow:wght@400&family=Barlow+Condensed:wght@400&display=swap"
)

# Not in the Figma exports yet. Name, family stack, size, line height,
# weight, letter spacing (all in px except weight).
TEXT_STYLES = [
    ("headline-medium", '"Barlow Condensed", "Arial Narrow", sans-serif', 28, 36, 400, 0),
    ("body-large", '"Barlow", system-ui, sans-serif', 16, 24, 400, 0.5),
]


def kebab(part):
    return re.sub(r"[^a-z0-9]+", "-", part.lower()).strip("-")


def var_name(collection, path, token):
    web = token.get("$extensions", {}).get("com.figma.codeSyntax", {}).get("WEB")
    if web:
        match = re.fullmatch(r"var\((--[A-Za-z0-9_-]+)\)", web.strip())
        if not match:
            sys.exit(f"Unexpected code syntax {web!r} on {collection}/{'/'.join(path)}")
        return match.group(1)
    return "--" + "-".join(kebab(p) for p in [collection, *path])


def css_value(collection, path, token):
    kind, value = token["$type"], token["$value"]
    where = f"{collection}/{'/'.join(path)}"
    if kind == "color":
        if not isinstance(value, dict) or "hex" not in value:
            sys.exit(f"Color token {where} has no hex value")
        if value.get("alpha", 1) != 1:
            sys.exit(f"Color token {where} has alpha {value['alpha']}; hex would drop it")
        return value["hex"].lower()
    if kind == "number":
        # Figma number variables are unitless pixels.
        return f"{value:g}px"
    sys.exit(f"Token {where} has unsupported type {kind!r}")


def flatten(node, path=()):
    """Yield (path, token) for every token in a nested group."""
    for key, child in node.items():
        if key.startswith("$") or not isinstance(child, dict):
            continue
        if "$value" in child:
            yield (*path, key), child
        else:
            yield from flatten(child, (*path, key))


def load_collection(name):
    files = sorted((TOKENS / name).glob("*.tokens.json"))
    if not files:
        sys.exit(f"No token files in {TOKENS / name}")
    modes = {}
    for f in files:
        data = json.loads(f.read_text(encoding="utf-8"))
        mode = data.get("$extensions", {}).get("com.figma.modeName", f.name.split(".")[0])
        modes[mode] = [
            (var_name(name, path, token), css_value(name, path, token))
            for path, token in flatten(data)
        ]
    if len(modes) == 1:
        return next(iter(modes.values())), []
    if set(modes) != {"Light", "Dark"}:
        sys.exit(f"Collection {name!r} has modes {sorted(modes)}; expected one mode, or Light and Dark")
    light_names = [n for n, _ in modes["Light"]]
    dark_names = [n for n, _ in modes["Dark"]]
    if sorted(light_names) != sorted(dark_names):
        sys.exit(f"Collection {name!r}: Light and Dark define different tokens")
    return modes["Light"], modes["Dark"]


def block(selector, decls, indent=""):
    lines = [f"{indent}{selector} {{"]
    lines += [f"{indent}  {name}: {value};" for name, value in decls]
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def main():
    light, dark = [], []
    for name in COLLECTIONS:
        l, d = load_collection(name)
        light += l
        dark += d

    for name, family, size, line_height, weight, tracking in TEXT_STYLES:
        light += [
            (f"--{name}-font-family", family),
            (f"--{name}-font-size", f"{size}px"),
            (f"--{name}-line-height", f"{line_height}px"),
            (f"--{name}-font-weight", str(weight)),
            (f"--{name}-letter-spacing", f"{tracking:g}px"),
        ]

    names = [n for n, _ in light]
    dupes = sorted({n for n in names if names.count(n) > 1})
    if dupes:
        sys.exit(f"Duplicate variable names: {', '.join(dupes)}")

    parts = [
        "/* Generated by build-tokens.py from tokens/. Do not edit by hand. */",
        f'@import url("{GOOGLE_FONTS}");',
        block(":root", light),
    ]
    if dark:
        # Dark values apply on screen only: print always uses Light, because
        # paper is white. :not([data-theme="light"]) lets an explicit light
        # choice beat a dark OS setting.
        parts.append(
            "@media screen and (prefers-color-scheme: dark) {\n"
            + block(':root:not([data-theme="light"])', dark, "  ")
            + "\n}"
        )
        parts.append("@media screen {\n" + block('[data-theme="dark"]', dark, "  ") + "\n}")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(HERE)} ({len(light)} variables, {len(dark)} dark overrides)")


if __name__ == "__main__":
    main()
